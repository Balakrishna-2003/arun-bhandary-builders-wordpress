<script>
document.addEventListener('DOMContentLoaded', function () {
    const items = document.querySelectorAll('.abb6-project-item');
    const infoDiv = document.getElementById('abb6PaginationInfo');
    const controlsDiv = document.getElementById('abb6PaginationControls');
    
    if (!items.length) {
        if (infoDiv) infoDiv.style.display = 'none';
        if (controlsDiv) controlsDiv.style.display = 'none';
        return;
    }

    const itemsPerPage = 6;
    let currentPage = 1;
    const totalPages = Math.ceil(items.length / itemsPerPage);

    function showPage(page) {
        currentPage = page;
        const start = (page - 1) * itemsPerPage;
        const end = start + itemsPerPage;

        // Show / Hide Project Items
        items.forEach((item, index) => {
            if (index >= start && index < end) {
                item.style.display = ''; // Reverts to default CSS display
            } else {
                item.style.display = 'none';
            }
        });

        // Update the Text Info
        if (infoDiv) {
            const endItem = Math.min(end, items.length);
            infoDiv.innerHTML = `Showing <strong>${start + 1}–${endItem}</strong> of <strong>${items.length}</strong> projects`;
        }

        renderControls();
    }

    function renderControls() {
        if (!controlsDiv) return;
        controlsDiv.innerHTML = '';

        // Previous Button
        const prevBtn = document.createElement('button');
        prevBtn.className = 'abb6-page-btn'; // Uses your theme's button styling
        prevBtn.innerHTML = '<i class="fa-solid fa-chevron-left"></i>';
        prevBtn.disabled = currentPage === 1;
        prevBtn.addEventListener('click', () => {
            if (currentPage > 1) showPage(currentPage - 1);
        });
        controlsDiv.appendChild(prevBtn);

        // Number Buttons
        for (let i = 1; i <= totalPages; i++) {
            const btn = document.createElement('button');
            // Adds an active class just in case your theme has one
            btn.className = `abb6-page-btn ${i === currentPage ? 'active' : ''}`;
            btn.innerText = i;
            btn.addEventListener('click', () => showPage(i));
            controlsDiv.appendChild(btn);
        }

        // Next Button
        const nextBtn = document.createElement('button');
        nextBtn.className = 'abb6-page-btn';
        nextBtn.innerHTML = '<i class="fa-solid fa-chevron-right"></i>';
        nextBtn.disabled = currentPage === totalPages;
        nextBtn.addEventListener('click', () => {
            if (currentPage < totalPages) showPage(currentPage + 1);
        });
        controlsDiv.appendChild(nextBtn);
    }

    // Initialize the first page
    showPage(1);
});
</script>

